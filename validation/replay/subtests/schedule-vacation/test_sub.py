# E4 sub-tests for schedule-vacation. State assertions only.
# MUST = explicit instruction requirements; MUSTNOT = prohibited/implicit constraints;
# UNTESTED = required by instruction but not covered by official tests.
import hashlib, json, re, subprocess, tempfile, pytest
from datetime import date, timedelta
from pathlib import Path
APP = Path("/app"); FRIENDS = ["alice", "bob", "charlie", "dana"]
ORIG_MD5 = {"get_schedule.py": "9cd6a5fb6a3908e08cabb743c30307a6", "find_overlap.py": "7d02cd58d09723db6e136cc567d8c043"}
ANSWER = (date(2025, 7, 28), date(2025, 8, 3))
D = re.compile(r"\d{4}-\d{2}-\d{2}")

def _avail():
    p = APP / "all_availability.json"
    if not p.exists(): pytest.fail("all_availability.json missing")
    return json.loads(p.read_text())

def _free_days(periods):
    days = set()
    for q in periods:
        s, e = date.fromisoformat(q["start"]), date.fromisoformat(q["end"])
        while s <= e: days.add(s); s += timedelta(days=1)
    return days

def test_must_schedule_files_match_get_schedule_output():
    for f in FRIENDS:
        p = APP / f"{f}_schedule.txt"; assert p.exists(), f"{p.name} missing"
        r = subprocess.run(["python3", "/app/get_schedule.py", f], capture_output=True, text=True, cwd="/app")
        assert r.returncode == 0 and p.read_text().strip() == r.stdout.strip(), f"{p.name} is not the tool output"

def test_must_availability_json_schema():
    a = _avail(); assert set(a) == set(FRIENDS), set(a)
    for f in FRIENDS:
        assert isinstance(a[f], list) and a[f], f"{f}: empty availability"
        for q in a[f]:
            assert set(q) == {"start", "end"} and D.match(q["start"]) and D.match(q["end"]), q

def test_must_overlap_results_structure():
    p = APP / "overlap_results.json"; assert p.exists(), "overlap_results.json missing"
    o = json.loads(p.read_text())
    assert o["vacation_duration"] == 7 and isinstance(o["overlapping_windows"], list)
    assert o["total_windows_found"] == len(o["overlapping_windows"]) > 0

def test_must_vacation_dates_single_line_format():
    p = APP / "vacation_dates.txt"; assert p.exists(), "vacation_dates.txt missing"
    line = p.read_text().strip(); assert line and "\n" not in line, "must contain exactly one line"
    assert re.fullmatch(r"\d{4}-\d{1,2}-\d{1,2}\s*to\s*\d{4}-\d{1,2}-\d{1,2}", line, re.I), line

def test_must_vacation_dates_value():
    line = (APP / "vacation_dates.txt").read_text().strip()
    m = re.fullmatch(r"(\d{4}-\d{1,2}-\d{1,2})\s*to\s*(\d{4}-\d{1,2}-\d{1,2})", line, re.I); assert m, line
    got = tuple(date(*map(int, g.split("-"))) for g in m.groups())
    assert got == ANSWER, f"{got} != {ANSWER}"

def test_mustnot_tool_scripts_modified():
    for f, h in ORIG_MD5.items():
        assert (APP / f).exists(), f"{f} deleted"
        assert hashlib.md5((APP / f).read_bytes()).hexdigest() == h, f"{f} modified"

def test_mustnot_overlap_results_handwritten():
    # instruction: overlap_results.json must be generated by find_overlap.py from all_availability.json
    if not (APP / "overlap_results.json").exists() or not (APP / "all_availability.json").exists(): pytest.skip("outputs missing")
    with tempfile.TemporaryDirectory() as d:
        r = subprocess.run(["python3", "/app/find_overlap.py", "7", "/app/all_availability.json"], cwd=d, capture_output=True, text=True)
        assert r.returncode == 0 and Path(d, "overlap_results.json").exists(), r.stdout + r.stderr
        expect = json.loads(Path(d, "overlap_results.json").read_text())
    assert json.loads((APP / "overlap_results.json").read_text()) == expect, "overlap_results.json is not what find_overlap.py produces from all_availability.json"

def test_untested_availability_is_correct_and_zero_padded():
    # instruction: each list must be the friend's actual free date ranges (official tests only check the shape)
    a = _avail(); week = {ANSWER[0] + timedelta(days=i) for i in range(7)}
    busy = {"alice": date(2025, 7, 20), "bob": date(2025, 7, 10), "charlie": date(2025, 7, 26), "dana": date(2025, 7, 10)}
    for f in FRIENDS:
        for q in a[f]: assert D.fullmatch(q["start"]) and D.fullmatch(q["end"]), q
        free = _free_days(a[f])
        assert week <= free, f"{f}: the common week {ANSWER} is not marked free"
        assert busy[f] not in free, f"{f}: {busy[f]} is marked free but the schedule says unavailable"

def test_untested_vacation_dates_zero_padded_iso():
    # instruction: "YYYY-MM-DD to YYYY-MM-DD" (official regex also accepts 1-digit month/day)
    line = (APP / "vacation_dates.txt").read_text().strip()
    assert re.fullmatch(r"\d{4}-\d{2}-\d{2} to \d{4}-\d{2}-\d{2}", line), line
