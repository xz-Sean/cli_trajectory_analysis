# E4 sub-tests for gomoku-planner. State assertions only.
# MUST = explicit instruction requirements; MUSTNOT = prohibited/implicit constraints;
# UNTESTED = required by instruction but not covered by official tests.
import hashlib, re
from pathlib import Path
MOVE = Path("/app/move.txt"); BOARD = Path("/app/gomoku_board.png")
BOARD_MD5 = "1c8afdc3e5fdeff1da1632546dcd344c"   # generated by make.py in the Dockerfile (PIL, deterministic)
# full stone list from make.py (the official test omits white (10,8))
STONES = {(7,6),(7,7),(7,8),(6,7),(8,7),(6,6),(8,8),(5,5),(5,6),(9,9),(9,7),(10,8)}

def _move():
    parts = MOVE.read_text().strip().split(",")
    return int(parts[0]), int(parts[1])

def test_must_move_file_exists():
    assert MOVE.is_file() and MOVE.read_text().strip() != ""

def test_must_move_is_row_comma_col_integers():
    parts = MOVE.read_text().strip().split(",")
    assert len(parts) == 2, parts
    int(parts[0]); int(parts[1])

def test_must_move_within_board():
    r, c = _move(); assert 0 <= r <= 14 and 0 <= c <= 14, (r, c)

def test_must_move_on_empty_point():
    assert _move() not in STONES, _move()

def test_must_move_blocks_white_three_in_row_7():
    # white (7,6),(7,7),(7,8) is the only immediate threat; blocking requires (7,5) or (7,9)
    r, c = _move(); assert r == 7 and c in (5, 9), (r, c)

def test_mustnot_board_image_modified():
    assert BOARD.is_file() and hashlib.md5(BOARD.read_bytes()).hexdigest() == BOARD_MD5

def test_untested_exact_format_no_spaces_single_line():
    # instruction: "[row],[col]" e.g. "7,7"; official test tolerates "7, 9" / extra whitespace
    assert re.fullmatch(r"\d{1,2},\d{1,2}", MOVE.read_text().strip()), repr(MOVE.read_text())
